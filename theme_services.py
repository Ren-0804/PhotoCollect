DEFAULT_THEME_NAME = "graphite"


def normalize_theme_name(value: str) -> str:
    name = str(value or "").strip().lower()
    return name if name in THEME_PALETTES else DEFAULT_THEME_NAME


def get_theme_palette(value: str) -> ThemePalette:
    return THEME_PALETTES[normalize_theme_name(value)]
