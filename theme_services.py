"""Pure palette registry; business modules never depend on theme selection."""

from __future__ import annotations

from dataclasses import dataclass


REQUIRED_THEME_KEYS = (
    "BG_MAIN",
    "BG_SIDEBAR",
    "BG_CARD",
    "BG_SUBTLE",
    "BG_ACTIVE",
    "PRIMARY",
    "PRIMARY_HOVER",
    "PRIMARY_SOFT",
    "TEXT_MAIN",
    "TEXT_SEC",
    "TEXT_MUTED",
    "TEXT_INVERT",
    "BORDER",
    "BORDER_HOVER",
    "SUCCESS",
    "SUCCESS_SOFT",
    "SUCCESS_LINE",
    "ERROR",
    "ERROR_SOFT",
    "ERROR_LINE",
    "WARNING",
    "WARNING_SOFT",
    "WARNING_LINE",
    "INK_ELEVATED",
    "INK_BORDER",
    "ACCENT_ON_DARK",
    "TEXT_ON_INK",
    "SCROLL_HANDLE",
    "SCROLL_HANDLE_HOVER",
)


@dataclass(frozen=True)
class ThemePalette:
    name: str
    display_name: str
    description: str
    colors: dict[str, str]


def _palette(name: str, display_name: str, description: str, **colors) -> ThemePalette:
    normalized = {key: str(value).upper() for key, value in colors.items()}
    missing = set(REQUIRED_THEME_KEYS) - set(normalized)
    extra = set(normalized) - set(REQUIRED_THEME_KEYS)
    if missing or extra:
        raise ValueError(f"Invalid palette {name}: missing={missing}, extra={extra}")
    return ThemePalette(name, display_name, description, normalized)


